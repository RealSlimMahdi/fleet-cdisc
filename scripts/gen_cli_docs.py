#!/usr/bin/env python3
"""Generate ``docs/getting-started/cli.md`` from the live argparse tree.

Usage
-----
Regenerate the CLI reference (written under docs/getting-started):

    uv run python scripts/gen_cli_docs.py

CI stale-check (exits 1 if the doc is out of date):

    uv run python scripts/gen_cli_docs.py --check

The reference is derived directly from :func:`fleet.cli._build_parser`, so
adding a command / flag in ``src/fleet/cli.py`` and re-running this script
keeps the docs in lock-step with the parser — no hand-maintained tables to
drift out of sync.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Make ``fleet`` importable when run from the repo root.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from fleet._version import __version__  # noqa: E402
from fleet.cli import _build_parser  # noqa: E402

_OUTPUT = Path(__file__).resolve().parent.parent / "docs" / "getting-started" / "cli.md"

_PREAMBLE = f"""# CLI Reference

<!-- AUTO-GENERATED by scripts/gen_cli_docs.py — do not edit by hand.
     Regenerate with: uv run python scripts/gen_cli_docs.py -->

Fleet ships the `fleet` command-line tool (version `{__version__}`) for
bootstrapping studies, executing derivation pipelines, validating datasets,
generating Define-XML, managing CDISC Controlled Terminology, and rendering
TLGs. Commands that query the CDISC Library require a valid `CDISC_API_KEY` —
set it in a `.env` file at your project root or as an environment variable.

```bash title=".env"
CDISC_API_KEY=your-api-key-here
```

## Conventions

- **Config discovery** — every command that needs `study_config.yaml` finds
  it git-style: the current directory first, then each parent. Pass
  `--config <path>` to override.
- **Exit codes** — `0` success, `1` on a Fleet error (a single clean message
  on stderr), `2` on a usage error (missing/unknown command or flag).
- **Errors** go to **stderr**; results go to stdout.
- `fleet --version` prints the installed version.

Run `fleet <command> --help` for the authoritative, always-current usage.
"""


def _format_choices(action: argparse.Action) -> str:
    if action.choices:
        return "`" + "`, `".join(str(c) for c in action.choices) + "`"
    return ""


def _default_str(action: argparse.Action) -> str:
    if action.required:
        return "_(required)_"
    if action.default is None or action.default is False:
        return "_(none)_"
    if action.default is True:
        return "_(on)_"
    if action.default == "":
        return '`""`'
    return f"`{action.default}`"


def _option_names(action: argparse.Action) -> str:
    return " / ".join(f"`{opt}`" for opt in action.option_strings)


def _render_parser(
    name: str,
    parser: argparse.ArgumentParser,
    lines: list[str],
    *,
    level: int = 2,
    prefix: str = "",
) -> None:
    """Emit a section for one (sub)parser, recursing into subcommands."""
    full = f"{prefix}{name}".strip()
    heading = "#" * level
    lines.append(f"{heading} `fleet {full}`")
    lines.append("")
    if (
        parser.description
        and parser.description != "Fleet — CDISC SDTM/ADaM derivation toolkit CLI."
    ):
        lines.append(parser.description)
        lines.append("")

    positionals: list[argparse.Action] = []
    options: list[argparse.Action] = []
    subparsers: argparse._SubParsersAction | None = None

    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            subparsers = action
        elif isinstance(action, argparse._HelpAction):
            continue
        elif action.option_strings:
            options.append(action)
        else:
            positionals.append(action)

    if positionals:
        lines.append("| Argument | Description |")
        lines.append("| -------- | ----------- |")
        for action in positionals:
            help_text = (action.help or "").replace("|", "\\|")
            lines.append(f"| `{action.dest}` | {help_text} |")
        lines.append("")

    if options:
        lines.append("| Option | Default | Description |")
        lines.append("| ------ | ------- | ----------- |")
        for action in options:
            help_text = (action.help or "").replace("|", "\\|")
            choices = _format_choices(action)
            if choices:
                help_text = f"{help_text} Choices: {choices}."
            lines.append(f"| {_option_names(action)} | {_default_str(action)} | {help_text} |")
        lines.append("")

    if subparsers is not None:
        for sub_name, sub_parser in subparsers.choices.items():
            _render_parser(
                sub_name,
                sub_parser,
                lines,
                level=min(level + 1, 4),
                prefix=f"{full} ",
            )


def render() -> str:
    parser = _build_parser()
    lines: list[str] = [_PREAMBLE, ""]

    # Command inventory table.
    sub_action = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    lines.append("## Command inventory")
    lines.append("")
    lines.append("| Command | What it does |")
    lines.append("| ------- | ------------ |")
    for name, sub in sub_action.choices.items():
        help_text = (sub.description or sub.prog).replace("|", "\\|")
        # Prefer the short help registered on the subparser action.
        for choice_action in sub_action._choices_actions:
            if choice_action.dest == name:
                help_text = (choice_action.help or help_text).replace("|", "\\|")
                break
        lines.append(f"| [`fleet {name}`](#fleet-{name}) | {help_text} |")
    lines.append("")
    lines.append("---")
    lines.append("")

    # Per-command sections.
    for name, sub in sub_action.choices.items():
        _render_parser(name, sub, lines, level=2)
        lines.append("---")
        lines.append("")

    text = "\n".join(lines).rstrip() + "\n"
    # Collapse accidental triple blank lines.
    while "\n\n\n" in text:
        text = text.replace("\n\n\n", "\n\n")
    return text


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--output", default=str(_OUTPUT), help="Output markdown path.")
    ap.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if the file is out of date (do not write).",
    )
    args = ap.parse_args(argv)

    content = render()
    out_path = Path(args.output)

    if args.check:
        current = out_path.read_text(encoding="utf-8") if out_path.is_file() else ""
        if current != content:
            print(f"{out_path} is out of date — run: uv run python scripts/gen_cli_docs.py")
            return 1
        print(f"{out_path} is up to date.")
        return 0

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding="utf-8")
    print(f"Wrote {out_path} ({content.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
