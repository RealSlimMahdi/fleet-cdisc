"""Tests for the define-spec scaffolder (``fleet.core.scaffolder``).

Network-free: ``_write_define`` takes already-assembled dataset metadata,
so the CDISC Library client is never touched.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, cast

import yaml

from fleet.core.scaffolder import DefineScaffolder, schema_directive

_DATASETS: list[dict[str, Any]] = [
    {
        "name": "DM",
        "label": "Demographics",
        "variables": [{"name": "USUBJID", "label": "Unique Subject Identifier", "type": "text"}],
    }
]


def _scaffold(tmp_path: Path) -> Path:
    scaffolder = DefineScaffolder(cast(Any, None))
    return scaffolder._write_define(
        study_id="STUDY01",
        company="Pharma Inc",
        standard="SDTMIG",
        standard_version="3.4",
        ct_version="2023-12-15",
        datasets=_DATASETS,
        output_path=tmp_path / "metadata" / "sdtm" / "define.yaml",
    )


class TestSchemaDirective:
    """Scaffolded specs carry no ``$schema`` header (#71).

    Fleet's own language server validates against the schema in the
    installed package, so a second validator pointed at a file path
    reports every violation twice — and that path rots as soon as Fleet
    is reinstalled elsewhere.
    """

    def test_scaffolded_spec_has_no_schema_header(self, tmp_path: Path) -> None:
        text = _scaffold(tmp_path).read_text(encoding="utf-8")

        assert "yaml-language-server" not in text

    def test_scaffolded_spec_keeps_its_human_header(self, tmp_path: Path) -> None:
        text = _scaffold(tmp_path).read_text(encoding="utf-8")

        assert text.startswith("# SDTMIG Define Specification — STUDY01")
        assert "Auto-generated by `fleet init define`" in text

    def test_scaffolded_spec_is_still_valid_yaml(self, tmp_path: Path) -> None:
        spec = yaml.safe_load(_scaffold(tmp_path).read_text(encoding="utf-8"))

        assert spec["study"]["id"] == "STUDY01"
        assert spec["datasets"][0]["name"] == "DM"

    def test_directive_is_offered_and_resolves(self, tmp_path: Path) -> None:
        """The opt-in line must point at a schema that is actually there."""
        spec_path = tmp_path / "metadata" / "sdtm" / "define.yaml"
        spec_path.parent.mkdir(parents=True)

        directive = schema_directive(spec_path)

        assert directive.startswith("# yaml-language-server: $schema=")
        target = directive.split("=", 1)[1]
        assert (spec_path.parent / target).resolve().is_file()
