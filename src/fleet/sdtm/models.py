"""SDTM data models: algorithm enum and YAML specification structures.

The per-algorithm variable models are generated from the central spec
registry (:mod:`fleet.core.spec_registry`) — the single source of truth
for spec-executable verbs.  ``SDTMAlgorithm`` stays literal source code
for import stability; a sync test asserts it always matches the registry.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum
from typing import Any

from pydantic import BaseModel

from fleet.core.spec_registry import (
    SpecVariableBase,
    parse_variable_spec,
    variable_spec_union,
)


class SDTMAlgorithm(StrEnum):
    """Derivation verbs for SDTM variable mappings.

    Kept in sync with ``fleet.core.spec_registry`` by
    ``tests/unit/test_spec_parity.py``.
    """

    ASSIGN_NO_CT = "assign_no_ct"
    ASSIGN_CT = "assign_ct"
    ASSIGN_DTC = "assign_dtc"
    HARDCODE_CT = "hardcode_ct"
    HARDCODE_NO_CT = "hardcode_no_ct"
    CONDITION_ADD = "condition_add"
    IF_THEN_ELSE = "if_then_else"
    AE_AEREL = "ae_aerel"
    MERGE = "merge"
    GROUP_BY = "group_by"
    DATASET_LEVEL = "dataset_level"
    NOTSUBMITTED = "notsubmitted"
    MULTIPLE_RESPONSES = "multiple_responses"
    DATE = "date"
    DURATION = "duration"
    SEQ = "seq"
    NSV = "nsv"
    CALLABLE = "callable"


@dataclass(frozen=True, slots=True)
class NSVMeta:
    """Metadata for a Non-Standard Variable (qualifier)."""

    target: str
    label: str
    origin: str = "DERIVED"
    evaluator: str | None = None


#: Discriminated union of all per-algorithm SDTM variable models.
#: Use in type annotations / Pydantic fields.
SDTMVariableSpecUnion = variable_spec_union("sdtm")


def SDTMVariableSpec(**data: Any) -> SpecVariableBase:  # noqa: N802 — back-compat factory
    """Validate a single SDTM variable spec (back-compat factory).

    Dispatches on ``algorithm`` to the strict per-algorithm model
    generated by :mod:`fleet.core.spec_registry`.  Unknown keys and
    missing required fields raise ``pydantic.ValidationError``.

    Args:
        **data: Spec fields including ``target`` and ``algorithm``.

    Returns:
        SpecVariableBase: The validated per-algorithm model instance.

    Examples:
        Validate a controlled-terminology assignment::

            from fleet.sdtm.models import SDTMVariableSpec

            var = SDTMVariableSpec(
                target="SEX", algorithm="assign_ct",
                source="sex_raw", ct_codelist="C66731",
            )
    """
    return parse_variable_spec("sdtm", data)


class SDTMDomainSpec(BaseModel):
    """Full specification for an SDTM domain derivation."""

    domain: str
    description: str | None = None
    fleet_spec_version: int | None = None
    variables: list[SDTMVariableSpecUnion]

    model_config = {"extra": "allow"}
