"""ADaM data models: algorithm enum and YAML specification structures.

The per-algorithm variable models are generated from the central spec
registry (:mod:`fleet.core.spec_registry`) — the single source of truth
for spec-executable verbs.  ``ADAMAlgorithm`` stays literal source code
for import stability; a sync test asserts it always matches the registry.
"""

from __future__ import annotations

from enum import StrEnum
from typing import Any

from pydantic import BaseModel

from fleet.core.spec_registry import (
    SpecVariableBase,
    parse_variable_spec,
    variable_spec_union,
)


class ADAMAlgorithm(StrEnum):
    """Derivation verbs for ADaM variable derivations.

    Kept in sync with ``fleet.core.spec_registry`` by
    ``tests/unit/test_spec_parity.py``.
    """

    # Base verbs
    SOURCE = "source"
    DERIVATION = "derivation"
    ASSIGNED = "assigned"
    RECODE = "recode"
    RENAME = "rename"
    CONDDERIVATION = "condderivation"
    LOOKUP = "lookup"
    WHERECLAUSES = "whereclauses"
    # BDS first-class methods (also valid as direct YAML algorithm keys)
    STUDY_DAY = "study_day"
    BASELINE = "baseline"
    CHG = "chg"
    PCHG = "pchg"
    FLAG = "flag"
    BMI = "bmi"
    NRIND = "nrind"
    ON_TREATMENT = "on_treatment"
    SHIFT = "shift"
    SEQ = "seq"
    BSA = "bsa"
    MAP = "map"
    MEAN_ARTERIAL_PRESSURE = "mean_arterial_pressure"
    QTC = "qtc"
    ATOXGR = "atoxgr"
    COMBINE_GRADES = "combine_grades"
    DATE = "date"
    DURATION = "duration"
    PICK = "pick"
    # ADSL subject-level aggregations (pin-resolved event datasets)
    FIRST_DATE = "first_date"
    LAST_DATE = "last_date"
    COUNT_EVENTS = "count_events"
    COUNT = "count"  # documented alias of count_events
    CALLABLE = "callable"


#: Discriminated union of all per-algorithm ADaM variable models.
#: Use in type annotations / Pydantic fields.
ADAMVariableSpecUnion = variable_spec_union("adam")


def ADAMVariableSpec(**data: Any) -> SpecVariableBase:  # noqa: N802 — back-compat factory
    """Validate a single ADaM variable spec (back-compat factory).

    Dispatches on ``algorithm`` to the strict per-algorithm model
    generated by :mod:`fleet.core.spec_registry`.  Unknown keys and
    missing required fields raise ``pydantic.ValidationError``.

    Args:
        **data: Spec fields including ``target`` and ``algorithm``.

    Returns:
        SpecVariableBase: The validated per-algorithm model instance.

    Examples:
        Validate a change-from-baseline derivation::

            from fleet.adam.models import ADAMVariableSpec

            var = ADAMVariableSpec(
                target="CHG", algorithm="chg", aval="AVAL", base="BASE",
            )
    """
    return parse_variable_spec("adam", data)


class ADAMDatasetSpec(BaseModel):
    """Full specification for an ADaM dataset derivation."""

    dataset: str
    description: str | None = None
    fleet_spec_version: int | None = None
    variables: list[ADAMVariableSpecUnion]

    model_config = {"extra": "allow"}
